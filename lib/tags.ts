// Port of scripts/tags.py: maps the free-form raw tags onto one consistent vocabulary (used by search).
const RULES: [string, RegExp][] = [
  ['כניסה חינם', /^(חינם|כניסה חופשית|כניסה חינם)/],
  ['נגיש', /^נגיש|עגלות$|לעגלות|חנייה נגישה/],
  ['פריחה', /פריח/],
  ['עונתי', /^עונתי/],
  ['מותר עם כלבים', /^כלבים (מותרים|ברצועה)/],
  ['לינה', /^לינה/],
  ['תצפית', /תצפי|^נוף$|דרך נוף|שקיעה/],
  ['מים ומעיינות', /^מעיין|מים עד המותן/],
  ['צפרות', /צפרות/],
  ['פיקניק', /פיקניק/],
  ['מסלול הליכה קצר', /הליכה קצרה|הליכה של|שביל קל|שבילים קצרים|מסלול קצר|שביל מעגלי/],
  ['השכרת אופניים', /אופניים|גולףקארט/],
  ['האכלת חיות', /האכל/],
  ['בית קפה ומאפייה', /^בית קפה|ארוחת בוקר|^מאפייה/],
  ['ארוחות', /^מסעדה|ארוח(ות|ת) (שף|ערב|בהזמנה)|ארוחה אורגנית|בראנץ/],
  ['יין', /יין|^יקב$|סיורי יקב|חדר טעימות/],
  ['בירה ומשקאות', /מבשלת|מזקקה/],
  ['גבינות', /גבינ|חוות עיזים/],
  ['שמן זית', /שמן זית|בית בד/],
  ['צמחוני', /^צמחוני|^חלבי$/],
  ['אורגני', /^אורגני/],
  ['כשר', /^כשר$/],
  ['גלריות ואמנות', /גלרי|אומנות מקומית/],
  ['מוזיאון', /^מוזיאון/],
  ['מוזיקה והופעות', /מוזיקה|הופעות|קונצרט|מופע/],
  ['שוק', /^שוק/],
  ["יד שנייה ווינטג'", /יד שנייה|וינטג/],
  ['עסק חברתי', /עסק חברתי|הכשרה תעסוקתית|סחר הוגן/],
];
const ORDER = ['תצפית', 'מים ומעיינות', 'פריחה', 'צפרות', 'פיקניק', 'מסלול הליכה קצר', 'השכרת אופניים', 'האכלת חיות', 'בית קפה ומאפייה', 'ארוחות', 'יין', 'בירה ומשקאות', 'גבינות', 'שמן זית', 'צמחוני', 'אורגני', 'כשר', 'גלריות ואמנות', 'מוזיאון', 'מוזיקה והופעות', 'שוק', "יד שנייה ווינטג'", 'עסק חברתי', 'כניסה חינם', 'נגיש', 'עונתי', 'מותר עם כלבים', 'לינה'];

export function canonTags(raw: string[]): string[] {
  const out = new Set<string>();
  for (const r of raw) for (const [name, rx] of RULES) if (rx.test(r)) out.add(name);
  // one tag per idea: "פריחה" implies seasonal
  if (out.has('פריחה')) out.delete('עונתי');
  return [...out].sort((a, b) => ORDER.indexOf(a) - ORDER.indexOf(b));
}
