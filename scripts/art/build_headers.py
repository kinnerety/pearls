"""Builds lib/headers.ts from the header generators (header_zones.py, header_cats.py).
Run from the repo root: python3 scripts/art/build_headers.py
"אתרי אינטרנט" is not listed here: a missing key falls back to the home header (HERO_SVG)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import header_zones as z, header_cats as c

ZONES = {'צפון': z.north, 'מרכז': z.center, 'ירושלים והאזור': z.jerusalem, 'דרום': z.south}
CATS = {'טבע ונוף': c.nature, 'משהו לאכול': c.table_scene, 'יקבים, מבשלות ומזקקות': c.bottles, 'סדנאות': c.carpentry,
        'סיורים ומפגשים': c.street, 'חקלאות': c.agriculture, 'בעלי חיים': c.animals, 'יוצרים וחנויות': c.shop,
        'תרבות': c.culture, 'עגלות קפה': c.coffee_cart}

def rec(d):
    return '{\n' + ''.join(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(fn(), ensure_ascii=False)},\n' for k, fn in d.items()) + '}'

out = ('// GENERATED by scripts/art/build_headers.py — do not edit by hand; edit the generators in scripts/art/ and rerun.\n'
       '// Header illustrations for the region and category pages: inner SVG for viewBox 0 0 1200 440, like HERO_SVG in components/art.ts.\n'
       '// Keys: ZONE_HERO by cloud name (צפון / מרכז / ירושלים והאזור / דרום), CAT_HERO by category name (lib/config.ts CATS).\n'
       '// "אתרי אינטרנט" has no entry on purpose: a missing key falls back to the home header. Entrance motion = .hd-* rules in app/globals.css.\n'
       f'export const ZONE_HERO: Record<string, string> = {rec(ZONES)};\n'
       f'export const CAT_HERO: Record<string, string> = {rec(CATS)};\n')
root = os.path.dirname(os.path.dirname(HERE))
open(os.path.join(root, 'lib', 'headers.ts'), 'w').write(out)
print('lib/headers.ts', len(out), 'bytes')
